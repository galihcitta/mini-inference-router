import sys, re, duckdb
csv = sys.argv[1]
con = duckdb.connect()
con.execute(f"create table t as select * from read_csv_auto('{csv}', header=true)")
q = lambda s: con.execute(s).fetchall()
print("schema:", q("describe t"))
print("rows:", q("select count(*) from t"))
print("nulls:", q("select count(*) filter (where instruction is null), count(*) filter (where response is null), count(*) filter (where intent is null) from t"))
print("intents/categories:", q("select count(distinct intent), count(distinct category) from t"))
print("per category:", q("select category, count(distinct intent), count(*) from t group by 1 order by 1"))
print("per intent min/max:", q("select min(c), max(c) from (select intent, count(*) c from t group by 1)"))
print("distinct instructions:", q("select count(distinct instruction), count(distinct lower(trim(instruction))) from t"))
print("distinct responses:", q("select count(distinct response) from t"))
print("instr in >1 intent:", q("select count(*) from (select lower(trim(instruction)) i from t group by 1 having count(distinct intent)>1)"))
print("ex conflicting:", q("select lower(trim(instruction)) i, list(distinct intent) from t group by 1 having count(distinct intent)>1 limit 5"))
print("instr len words p50/p95/max:", q("select quantile_cont(len(string_split(instruction,' ')),[0.5,0.95]), max(len(string_split(instruction,' '))) from t"))
print("resp len words p50/p95/max:", q("select quantile_cont(len(string_split(response,' ')),[0.5,0.95]), max(len(string_split(response,' '))) from t"))
print("resp with placeholders:", q("select count(*) filter (where response like '%{{%'), count(*) from t"))
print("instr with placeholders:", q("select count(*) filter (where instruction like '%{{%') from t"))
print("top placeholders in instr:", q("select m, count(*) from (select unnest(regexp_extract_all(instruction, '\\{\\{[^}]+\\}\\}')) m from t) group by 1 order by 2 desc limit 8"))
flags = q("select flags from t")
from collections import Counter
c = Counter(ch for (f,) in flags for ch in (f or ""))
print("flag letters:", sorted(c.items(), key=lambda x:-x[1]))
print("flag W (offensive) rows:", sum(1 for (f,) in flags if f and 'W' in f))
print("sample K-only:", q("select instruction, intent from t where flags like '%K%' limit 4"))
print("sample response:", q("select intent, response from t where intent='track_refund' limit 1"))
